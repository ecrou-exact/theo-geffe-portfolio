var currentLang = localStorage.getItem('lang') || 'en';

function applyLang(lang) {
  currentLang = lang;
  localStorage.setItem('lang', lang);
  document.documentElement.setAttribute('lang', lang);

  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    var key = el.getAttribute('data-i18n');
    var entry = I18N[key];
    if (entry && entry[lang] !== undefined) el.innerHTML = entry[lang];
  });

  document.querySelectorAll('.lsw [data-l]').forEach(function (btn) {
    var on = btn.getAttribute('data-l') === lang;
    btn.classList.toggle('on', on);
    btn.setAttribute('aria-pressed', on ? 'true' : 'false');
  });
}

function initI18n() {
  applyLang(currentLang);
  document.querySelectorAll('.lsw [data-l]').forEach(function (btn) {
    btn.addEventListener('click', function () { applyLang(btn.getAttribute('data-l')); });
  });
}
